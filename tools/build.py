def load_sheets():
    out = {}
    for path in sorted(SHEETS.glob("*.json")):
        data = json.loads(path.read_text())
        out[data["sheet"]] = data["rows"]
    return out


def by_id(rows):
    return {r["id"]: r for r in rows}


def rgb(text):
    return [int(v) for v in text.split(",")]


# ---------------------------------------------------------------- scripts

def setting_default(cs2, sid):
    return float(cs2[sid]["default"])


UDF_DIR = "csnv"
# xNVSE caps an expression in parentheses at 512 characters, and an inline lambda counts as one, so every
# handler is its own function file in Data/NVSE/user_defined_functions/csnv/, fetched with CompileScript.


def udf_ref(name):
    return 'CompileScript "%s\\%s.txt"' % (UDF_DIR, name)


def header(L, args, what):
    L.append("begin Function {%s}" % args)
    L.append("; CS2 in the Mojave - %s." % what)
    L.append("; Generated by tools/build.py from sheets/*.json. Edit the sheets, not this file.")


def main_script(s):
    """csnv_main: runs on every load and new game (via ln_csnv.txt)."""
    weapons, cs2 = by_id(s["weapons"]), by_id(s["cs2_settings"])
    L = []
    a = L.append
    header(L, " ", "main script, run on every load and new game by Data/NVSE/Plugins/scripts/ln_csnv.txt")
    a("\tint iKey = 48")
    a("\tint iBad = 0")
    a("\tfloat fVal = 0")
    a("\tfloat fLen = %g" % (setting_default(cs2, "xhair_size") * 2))
    a("\tfloat fGap = %g" % (4 + setting_default(cs2, "xhair_gap")))
    a("\tfloat fThick = %g" % max(1, round(setting_default(cs2, "xhair_thickness") * 2)))
    a("\tfloat fDot = %g" % (2 if setting_default(cs2, "xhair_dot") else 1))
    a("\tref rForm")
    a("\tref rFn")
    a("\tref rCond")
    a("")
    a("\t; hook load_settings: values the launcher wrote from the player's CS2 files (0 = missing -> keep default)")
    a('\tlet fVal := GetINIFloat "Keys:BuyKey" "%s"' % INI)
    a("\tif fVal > 0")
    a("\t\tlet iKey := fVal")
    a("\tendif")
    for var, key in (("fLen", "Length"), ("fGap", "Gap"), ("fThick", "Thickness")):
        a('\tlet fVal := GetINIFloat "Crosshair:%s" "%s"' % (key, INI))
        a("\tif fVal > 0")
        a("\t\tlet %s := fVal" % var)
        a("\tendif")
    a('\tlet fVal := GetINIFloat "Crosshair:Dot" "%s"' % INI)
    a("\tif fVal > 0")
    a("\t\tlet fDot := 2")
    a("\tendif")
    a("")
    a("\t; hook resolve_forms: the launcher-built weapons in CSNV.esp, their ammo and caps")
    for w in weapons.values():
        for mod, fid, what in (("CSNV.esp", w["plugin_form"], "weapon %s" % w["name"]),
                               ("FalloutNV.esm", w["ammo_form"], "ammo for %s" % w["name"])):
            a('\tlet rForm := GetFormFromMod "%s" "%s"' % (mod, fid))
            a("\tif eval !(IsFormValid rForm)")
            a('\t\tPrintToConsole "CSNV error: %s %s (%s) not found"' % (mod, fid, what))
            a("\t\tlet iBad += 1")
            a("\tendif")
    a('\tlet rForm := GetFormFromMod "FalloutNV.esm" "00000F"')
    a('\tPlayerRef.AuxVarSetRef "*_CSNVCaps" rForm')
    a("")
    a("\t; once per game session: HUD layer and event handlers (they survive loading a save)")
    a('\tif eval !(PlayerRef.AuxVarGetFlt "*_CSNVSession")')
    a('\t\tPlayerRef.AuxVarSetFlt "*_CSNVSession" 1')
    a("\t\t; hook hud_overlay")
    a('\t\tInjectUIXML "HUDMainMenu" "Data\\menus\\csnv\\csnv_hud.xml"')
    a("\t\t; hook key_buy_menu (opens buy_screen_open)")
    a("\t\tlet rFn := %s" % udf_ref("csnv_onkey"))
    a("\t\tif eval IsFormValid rFn")
    a("\t\t\tSetOnKeyDownEventHandler rFn 1 iKey")
    a("\t\telse")
    a('\t\t\tPrintToConsole "CSNV error: csnv_onkey.txt did not compile"')
    a("\t\t\tlet iBad += 1")
    a("\t\tendif")
    a("\t\t; hook buy_screen_style: the game's message menu is 1001")
    a("\t\tlet rFn := %s" % udf_ref("csnv_onmenu"))
    a("\t\tif eval IsFormValid rFn")
    a("\t\t\tSetOnMenuOpenEventHandler rFn 1 1001")
    a("\t\telse")
    a('\t\t\tPrintToConsole "CSNV error: csnv_onmenu.txt did not compile"')
    a("\t\t\tlet iBad += 1")
    a("\t\tendif")
    a("\tendif")
    a("")
    a("\t; crosshair geometry from the player's CS2 settings (the colour is in xhair.dds, written by the launcher)")
    a('\tSetUIFloat "HUDMainMenu/CSNV_HUD/user0" fLen')
    a('\tSetUIFloat "HUDMainMenu/CSNV_HUD/user1" fGap')
    a('\tSetUIFloat "HUDMainMenu/CSNV_HUD/user2" fThick')
    a('\tSetUIFloat "HUDMainMenu/CSNV_HUD/user3" fDot')
    a("")
    a("\t; hook hud_update + hide_vanilla_hud: delayed calls are cleared on load, so this restarts every load")
    a("\tlet rFn := %s" % udf_ref("csnv_hudtick"))
    a("\tlet rCond := %s" % udf_ref("csnv_always"))
    a("\tif eval (IsFormValid rFn) && (IsFormValid rCond)")
    a("\t\tCallWhilePerSeconds 0.1 rFn rCond")
    a("\telse")
    a('\t\tPrintToConsole "CSNV error: the HUD scripts did not compile"')
    a("\t\tlet iBad += 1")
    a("\tendif")
    a("")
    a("\tif iBad > 0")
    a('\t\tPrintToConsole "CS2 in the Mojave: %g problem(s), see the CSNV error lines above." iBad')
    a("\telse")
    a('\t\tPrintToConsole "CS2 in the Mojave: ready. Buy key scancode %g." iKey')
    a("\tendif")
    a("end")
    return "\n".join(L) + "\n"


def onkey_script(s):
    """csnv_onkey: the player's CS2 buy key -> the buy screen (hooks key_buy_menu, buy_screen_open)."""
    weapons, buys = by_id(s["weapons"]), sorted(s["buy_menu"], key=lambda r: r["slot"])
    L = []
    a = L.append
    header(L, "int iPressed", "buy key handler (JIP SetOnKeyDownEventHandler)")
    a("\tref rBuy")
    a("\tref rCaps")
    a("\tfloat fCaps")
    a("\tif MenuMode")
    a("\t\treturn")
    a("\tendif")
    a("\tlet rBuy := %s" % udf_ref("csnv_buy"))
    a('\tlet rCaps := PlayerRef.AuxVarGetRef "*_CSNVCaps"')
    a("\tlet fCaps := PlayerRef.GetItemCount rCaps")
    a('\tPlayerRef.AuxVarSetFlt "*_CSNVBuyOpen" 1')
    buttons = "|".join("%s  $%d" % (weapons[b["weapon"]]["name"], b["price_caps"]) for b in buys)
    a('\tMessageBoxExAlt rBuy "^BUY MENU^You have %%.0f caps.|%s|Cancel" fCaps' % buttons)
    a("end")
    return "\n".join(L) + "\n"


def buy_script(s):
    """csnv_buy: the clicked button -> pay and give (hooks spend_caps, give_item)."""
    weapons, buys = by_id(s["weapons"]), sorted(s["buy_menu"], key=lambda r: r["slot"])
    L = []
    a = L.append
    header(L, "int iButton", "buy screen button handler (JIP MessageBoxExAlt callback, 0-based button)")
    a("\tref rW")
    a("\tref rA")
    a("\tref rC")
    a("\tint iPrice")
    a("\tint iAmmo")
    a("\tfloat fHave")
    a('\tPlayerRef.AuxVarSetFlt "*_CSNVBuyOpen" 0')
    for i, b in enumerate(buys):
        w = weapons[b["weapon"]]
        a("\t%s iButton == %d" % ("if" if i == 0 else "elseif", i))
        a('\t\tlet rW := GetFormFromMod "CSNV.esp" "%s"' % w["plugin_form"])
        a('\t\tlet rA := GetFormFromMod "FalloutNV.esm" "%s"' % w["ammo_form"])
        a("\t\tlet iPrice := %d" % b["price_caps"])
        a("\t\tlet iAmmo := %d" % w["starter_ammo"])
    a("\telse")
    a("\t\treturn")
    a("\tendif")
    a("\tif eval !(IsFormValid rW)")
    a('\t\tMessageEx "CS2 in the Mojave: that weapon is missing. Start the game from Melty."')
    a("\t\treturn")
    a("\tendif")
    a('\tlet rC := PlayerRef.AuxVarGetRef "*_CSNVCaps"')
    a("\t; hook spend_caps")
    a("\tlet fHave := PlayerRef.GetItemCount rC")
    a("\tif fHave < iPrice")
    a('\t\tMessageEx "Not enough caps: that costs %g." iPrice')
    a("\t\treturn")
    a("\tendif")
    a("\tPlayerRef.RemoveItem rC iPrice 1")
    a("\t; hook give_item")
    a("\tPlayerRef.AddItem rW 1 1")
    a("\tif eval IsFormValid rA")
    a("\t\tPlayerRef.AddItem rA iAmmo 1")
    a("\tendif")
    a("\tPlayerRef.EquipItem rW 0 1")
    a('\tMessageEx "Bought %n for %g caps." rW iPrice')
    a("end")
    return "\n".join(L) + "\n"


def onmenu_script(s):
    """csnv_onmenu: CS2 layer on the message menu, only while our buy screen opens (hook buy_screen_style)."""
    L = []
    a = L.append
    header(L, "int iMenu", "message menu open handler (JIP SetOnMenuOpenEventHandler)")
    a("\tref rCaps")
    a("\tfloat fCaps")
    a('\tlet fCaps := PlayerRef.AuxVarGetFlt "*_CSNVBuyOpen"')
    a("\tif fCaps == 0")
    a("\t\treturn")
    a("\tendif")
    a('\tInjectUIXML "MessageMenu" "Data\\menus\\csnv\\csnv_buy.xml"')
    a('\tlet rCaps := PlayerRef.AuxVarGetRef "*_CSNVCaps"')
    a("\tlet fCaps := PlayerRef.GetItemCount rCaps")
    a('\tSetUIStringEx "MessageMenu/CSNV_Buy/bs_caps/string" "$ %.0f" fCaps')
    a("end")
    return "\n".join(L) + "\n"


def hudtick_script(s):
    """csnv_hudtick: every 0.1 s, the HUD values (hooks hud_update, hide_vanilla_hud)."""
    hud, hide = by_id(s["hud"]), s["hud_hide"]
    L = []
    a = L.append
    header(L, " ", "HUD update, every 0.1 s (xNVSE CallWhilePerSeconds)")
    a("\tref rAm")
    a("\tref rC")
    a("\tfloat fClip")
    a("\tfloat fRes")
    a("\tfloat fNum")
    a("\tlet fNum := PlayerRef.GetAV Health")
    a('\tSetUIStringEx "HUDMainMenu/CSNV_HUD/hud_health/string" "%s" fNum'
      % hud["hud_health"]["format"].replace("{value}", "%.0f"))
    a("\tlet fNum := PlayerRef.GetAV DamageThreshold")
    a('\tSetUIStringEx "HUDMainMenu/CSNV_HUD/hud_armor/string" "%s" fNum'
      % hud["hud_armor"]["format"].replace("{value}", "%.0f"))
    a('\tlet rC := PlayerRef.AuxVarGetRef "*_CSNVCaps"')
    a("\tlet fNum := PlayerRef.GetItemCount rC")
    a('\tSetUIStringEx "HUDMainMenu/CSNV_HUD/hud_caps/string" "%s" fNum'
      % hud["hud_caps"]["format"].replace("{value}", "%.0f"))
    a("\tlet rAm := GetPlayerCurrentAmmo")
    a("\tif eval IsFormValid rAm")
    a("\t\tlet fClip := GetPlayerCurrentAmmoRounds")
    a("\t\tlet fRes := PlayerRef.GetItemCount rAm")
    a("\t\tlet fRes -= fClip")
    a("\t\tif fRes < 0")
    a("\t\t\tlet fRes := 0")
    a("\t\tendif")
    a('\t\tSetUIStringEx "HUDMainMenu/CSNV_HUD/hud_ammo/string" "%s" fClip fRes'
      % hud["hud_ammo"]["format"].replace("{clip}", "%.0f").replace("{reserve}", "%.0f"))
    a("\telse")
    a('\t\tSetUIStringEx "HUDMainMenu/CSNV_HUD/hud_ammo/string" " "')
    a("\tendif")
    for h in hide:
        a('\tSetUIFloat "HUDMainMenu/%s/visible" 0' % h["tile"])
    a("end")
    return "\n".join(L) + "\n"


