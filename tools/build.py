def check_script_limits(name, text):
    """Fail the build on what xNVSE rejects: >512 characters inside one pair of parentheses."""
    depth, start = 0, 0
    for i, ch in enumerate(text):
        if ch == "(":
            if depth == 0:
                start = i
            depth += 1
        elif ch == ")" and depth:
            depth -= 1
            if depth == 0 and i - start - 1 > 512:
                line = text.count("\n", 0, start) + 1
                sys.exit(f"{name}.txt line {line}: {i - start - 1} characters inside parentheses (xNVSE allows 512)")
    if "begin Function" in text and text.count("begin Function") > 1:
        sys.exit(f"{name}.txt: inline lambdas are not allowed; give the handler its own file")


