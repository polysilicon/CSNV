#!/usr/bin/env python3
"""Build Cyberpunk Kino from its sheets.

  python3 tools/build.py            generate scripts, strings and launcher tables, build the launcher
  python3 tools/build.py --release  also download the bundled tools (checked by SHA-256) and make
                                    build/CyberKino-<version>.zip

Generated from sheets/*.json:
  cet/cyberkino/data.lua     the CET mod's tables (guns, cyberware, zombies, rules, props, arena)
  launcher/sheets_gen.go     the launcher's tables (Ray Gun build, CET keys)

The release zip holds CyberKino/ (launcher, bundled tools) and CET/cyberkino/ (the CET mod).
"""
import argparse
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import urllib.request
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SHEETS = ROOT / "sheets"
BUILD = ROOT / "build"
VERSION_FILE = ROOT / "VERSION"


def sheet(name):
    return json.loads((SHEETS / f"{name}.json").read_text())["rows"]


# ---------------------------------------------------------------- CET data

def lua(v, indent=1):
    pad = "\t" * indent
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, str):
        return json.dumps(v)
    if isinstance(v, list):
        return "{\n" + "".join(f"{pad}{lua(x, indent + 1)},\n" for x in v) + "\t" * (indent - 1) + "}"
    if isinstance(v, dict):
        return "{\n" + "".join(f"{pad}{k} = {lua(x, indent + 1)},\n" for k, x in v.items()) + "\t" * (indent - 1) + "}"
    raise SystemExit(f"can't write {v!r} to Lua")


def strip(rows, drop=("source", "tested_in_game", "about")):
    return [{k: v for k, v in r.items() if k not in drop} for r in rows]


def data_lua():
    weapons = strip(sheet("weapons"))
    cyber = strip(sheet("cyberware"))
    zombies = strip(sheet("zombies"))
    boss = next(z for z in zombies if z["pool"] == "boss")
    d = {
        "version": VERSION_FILE.read_text().strip(),
        "weapons": weapons,
        "weaponsById": {},
        "startWeapon": next(w["id"] for w in weapons if w["role"] == "start"),
        "cyberware": cyber,
        "cyberwareById": {},
        "zombies": [z for z in zombies if z["pool"] != "boss"],
        "boss": boss,
        "rules": {r["id"]: r["value"] for r in sheet("rules")},
        "props": {p["id"]: p["entity"] for p in sheet("props")},
        "arena": {a["id"]: {"x": a["x"], "y": a["y"], "z": a["z"], "yaw": a["yaw"]} for a in sheet("arena")},
        "cyberwareAreas": ["SystemReplacementCW", "ArmsCW", "HandsCW", "EyesCW", "FrontalCortexCW", "MusculoskeletalSystemCW",
                           "NervousSystemCW", "CardiovascularSystemCW", "ImmuneSystemCW", "IntegumentarySystemCW", "LegsCW", "FaceCW"],
    }
    body = lua(d)
    body = body.replace("weaponsById = {\n\t},", "weaponsById = {},").replace("cyberwareById = {\n\t},", "cyberwareById = {},")
    return ("-- Generated by tools/build.py from sheets/*.json. Do not edit.\n"
            "local d = " + body + "\n"
            "for _, w in ipairs(d.weapons) do d.weaponsById[w.id] = w end\n"
            "for _, c in ipairs(d.cyberware) do d.cyberwareById[c.id] = c end\n"
            "return d\n")


def generate():
    out = {"cet/cyberkino/data.lua": data_lua(), "launcher/sheets_gen.go": go_tables()}
    for rel, text in out.items():
        path = ROOT / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, newline="")
        print(f"generated {rel}")
    if shutil.which("luajit"):
        for f in ("cet/cyberkino/init.lua", "cet/cyberkino/data.lua"):
            subprocess.run(["luajit", "-bl", str(ROOT / f)], stdout=subprocess.DEVNULL, check=True)
        print("Lua syntax checked")


# ---------------------------------------------------------------- launcher tables

def go_string(s):
    return json.dumps(s)


def go_tables():
    r = sheet("raygun")[0]
    lines = ["// Code generated by tools/build.py from sheets/*.json. DO NOT EDIT.", "", "package main", "",
             f"const modVersion = {go_string(VERSION_FILE.read_text().strip())}", "",
             f"const cetModName = {go_string('cyberkino')}", "",
             f"var rayGun = rayGunSpec{{Zone: {go_string(r['bo_zone'])}, Weapon: {go_string(r['bo_weapon'])}, DonorMesh: {go_string(r['cp_donor_mesh'])}, "
             f"HidePrefix: {go_string(r['cp_hide_prefix'])}, Archive: {go_string(r['archive'])}, FitScale: {r['fit_scale']}}}", "",
             "var keyRows = []keySpec{"]
    for k in sheet("keys"):
        lines.append(f"\t{{ID: {go_string(k['id'])}, VK: {k['vk']}}},")
    lines += ["}", ""]
    return "\n".join(lines)


# ---------------------------------------------------------------- launcher and release

def build_launcher(stage):
    env = dict(os.environ, GOOS="windows", GOARCH="amd64", CGO_ENABLED="0")
    out = stage / "cyberkino-launch.exe"
    subprocess.run(["go", "build", "-trimpath", "-ldflags", "-s -w", "-o", str(out), "."], cwd=ROOT / "launcher", env=env, check=True)
    print(f"built {out.relative_to(ROOT)}")


def download(tool, cache):
    cache.mkdir(parents=True, exist_ok=True)
    dest = cache / Path(tool["url"]).name
    if not dest.exists() or hashlib.sha256(dest.read_bytes()).hexdigest() != tool["sha256"]:
        print(f"downloading {tool['url']}")
        with urllib.request.urlopen(tool["url"]) as r, open(dest, "wb") as f:
            shutil.copyfileobj(r, f)
    digest = hashlib.sha256(dest.read_bytes()).hexdigest()
    if digest != tool["sha256"]:
        raise SystemExit(f"{tool['id']}: SHA-256 {digest} does not match the tools sheet")
    return dest


def release(stage, version):
    tools_dir = stage / "tools"
    for tool in sheet("tools"):
        archive = download(tool, BUILD / "dl")
        target = tools_dir / tool["bundle_dir"]
        if target.exists():
            shutil.rmtree(target)
        with zipfile.ZipFile(archive) as z:
            for info in z.infolist():
                name = info.filename.replace("\\", "/")
                if name.endswith("/") or ".." in name.split("/"):
                    continue
                # OAT's raw/ folder holds templates for other games; T5 needs only its own
                if tool["id"] == "oat" and name.startswith("raw/") and not name.startswith("raw/t5/"):
                    continue
                dest = target / name
                dest.parent.mkdir(parents=True, exist_ok=True)
                dest.write_bytes(z.read(info))
    zip_path = BUILD / f"CyberKino-{version}.zip"
    if zip_path.exists():
        zip_path.unlink()
    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        for path in sorted(stage.rglob("*")):
            if path.is_file():
                z.write(path, Path("CyberKino") / path.relative_to(stage))
        cet = stage.parent / "stage_cet"
        for path in sorted(cet.rglob("*")):
            if path.is_file() and path.name != "cyberkino.log":
                z.write(path, Path("CET") / path.relative_to(cet))
    digest = hashlib.sha256(zip_path.read_bytes()).hexdigest()
    print(f"release {zip_path.relative_to(ROOT)}: {zip_path.stat().st_size} bytes, sha256 {digest}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--release", action="store_true")
    args = ap.parse_args()
    if subprocess.run([sys.executable, str(ROOT / "tools/preflight.py")]).returncode != 0:
        raise SystemExit("preflight is not clean: fix the sheets first")
    generate()
    version = VERSION_FILE.read_text().strip()
    stage = BUILD / "stage"
    if stage.exists():
        shutil.rmtree(stage)
    stage.mkdir(parents=True)
    build_launcher(stage)
    cet = stage.parent / "stage_cet" / "cyberkino"
    if cet.parent.exists():
        shutil.rmtree(cet.parent)
    shutil.copytree(ROOT / "cet/cyberkino", cet)
    for doc in ("README.md", "CREDITS.md", "LICENSE"):
        shutil.copy(ROOT / doc, stage / doc)
    shutil.copytree(ROOT / "licenses", stage / "licenses")
    if args.release:
        release(stage, version)


if __name__ == "__main__":
    main()
