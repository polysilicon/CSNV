"""Prints the lobby's mastery tags (one per PvP character, kit-menu order) for cosmetics.tags in
crispylobby/res/config.yml. A tag unlocks when the player's mastery XP for that character (pvp.mx<id> on the PvP
server) reaches Master. Re-run and paste over the block between the "mastery tags" markers after adding a kit."""
import json, os, sys
sys.argv = sys.argv[:1]
import build

CODES = {"black": "0", "dark_blue": "1", "dark_green": "2", "dark_aqua": "3", "dark_red": "4", "dark_purple": "5",
         "gold": "6", "gray": "7", "dark_gray": "8", "blue": "9", "green": "a", "aqua": "b", "red": "c",
         "light_purple": "d", "yellow": "e", "white": "f"}
HEAD_KEY = {"samurai": "edgerunner", "assassin": "lucy"}   # kits whose head is stored under another name

heads = json.load(open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "heads.json")))
kits = {k[0]: k for k in build.KITS}
print("    # ---- mastery tags (generated by pvp/mastery_tags.py): master that PvP character")
for i in build.KIT_ORDER:
    kid, key, name, color = kits[i][:4]
    head = heads.get(HEAD_KEY.get(key, key))
    print(f'    m_{key}: {{display: "&{CODES[color]}[★ {name}]", icon: PLAYER_HEAD, score: pvp.mx{kid}, min: {build.MASTERY[-1]}, '
          f'note: "{name}"' + (f', head: "{head}"' if head else "") + "}")
print("    # ---- end of mastery tags")
