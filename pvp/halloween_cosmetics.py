"""Adds the Haunted Night (Halloween) cosmetics to a CrispyLobby config.yml: the event tags, name colours and chat
colours from build.HW_COSMETICS, each unlocked by its pvp.hw<n> score on the Multiverse server. Each block sits
between "# ---- halloween" markers at the end of cosmetics.tags / name-colors / chat-colors; re-running replaces them.

    python3 halloween_cosmetics.py <config.yml> [...]
"""
import re
import sys

files, sys.argv = sys.argv[1:], sys.argv[:1]
import build

ICONS = {"hw_pumpkin": "ORANGE_DYE", "hw_candycorn": "YELLOW_DYE", "hw_witchbrew": "LIME_DYE", "hw_bloodmoon": "RED_DYE",
         "hw_ghostly": "WHITE_DYE", "hw_pumpkinspice": "ORANGE_DYE", "hw_spectral": "LIGHT_BLUE_DYE"}
TAG_ICONS = {"hw_lostmyhead": "NETHERITE_HOE", "hw_pumpkinking": "JACK_O_LANTERN", "hw_spookyscary": "SKELETON_SKULL",
             "hw_crispyhalloween": "JACK_O_LANTERN", "hw_trickortreat": "COOKIE", "hw_slasher": "IRON_SWORD"}
START, END = "    # ---- halloween (generated by pvp/halloween_cosmetics.py): win them in Haunted Night", "    # ---- end of halloween"


def block(kind):
    rows = []
    for (n, k, lid, name, code) in build.HW_COSMETICS:
        if k != kind: continue
        if kind == "tag":
            rows.append(f'    {lid}: {{display: "{code}", icon: {TAG_ICONS[lid]}, score: pvp.hw{n}, min: 1, note: "Haunted Night"}}')
        else:
            rows.append(f'    {lid}: {{name: "{name}", code: "{code}", cost: 0, icon: {ICONS[lid]}, score: pvp.hw{n}}}')
    return [START] + rows + [END]


def apply(path):
    lines = open(path, encoding="utf-8").read().split("\n")
    out, skip = [], False
    for l in lines:   # drop old blocks
        if l == START: skip = True
        if not skip: out.append(l)
        if skip and l == END: skip = False
    lines = out
    for section, kind in (("tags", "tag"), ("name-colors", "name"), ("chat-colors", "chat")):
        head = lines.index(f"  {section}:")
        end = head + 1
        while end < len(lines) and (lines[end].startswith("    ") or lines[end].strip() == ""):
            end += 1
        while lines[end - 1].strip() == "": end -= 1   # after the section's last entry
        lines[end:end] = block(kind)
    open(path, "w", encoding="utf-8").write("\n".join(lines))
    print(f"{path}: {len(build.HW_COSMETICS)} Halloween cosmetics")


for f in files: apply(f)
